/**
 * 주어진 단어가 실무 단어 목록에 있는지 확인
 */
function isPracticalWord(word) {
  if (!word || word.length === 0) return false;

  for (const category in PRACTICAL_WORDS) {
    if (PRACTICAL_WORDS[category].includes(word)) {
      return true;
    }
  }
  return false;
}

/**
 * 단어가 어떤 카테고리에 속하는지 확인
 */
function getWordCategory(word) {
  for (const category in PRACTICAL_WORDS) {
    if (PRACTICAL_WORDS[category].includes(word)) {
      return category;
    }
  }
  return null;
}

/**
 * 모든 실무 단어 리스트 반환
 */
function getAllPracticalWords() {
  const all = [];
  for (const category in PRACTICAL_WORDS) {
    all.push(...PRACTICAL_WORDS[category]);
  }
  return all;
}

